import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { randomBytes, createHmac, randomUUID } from "node:crypto";
import { db } from "../../api/src/db";
import { digest, sessionCookie } from "../../api/src/security";
import { processWhatsappEvent } from "../../api/src/whatsapp-service";
const userIds: string[] = [], propertyIds: string[] = [], keys: string[] = [];
test.afterAll(async () => {
  await db.whatsappReply.deleteMany({ where: { eventKey: { in: keys } } });
  await db.whatsappInboxEvent.deleteMany({ where: { eventKey: { in: keys } } });
  await db.property.deleteMany({ where: { id: { in: propertyIds } } });
  await db.user.deleteMany({ where: { id: { in: userIds } } });
  await db.$disconnect();
});
test("WhatsApp: gerar código, confirmar vínculo, trocar propriedade e desconectar em desktop/celular", async ({ page, context, request }) => {
  const user = await db.user.create({ data: { email: `wa-${randomUUID()}@example.test`, name: "Maria do Campo", passwordHash: "synthetic", emailVerifiedAt: new Date() } }); userIds.push(user.id);
  const properties = await Promise.all(["Sítio Girassol", "Fazenda Horizonte"].map(name => db.property.create({ data: { name, responsible: user.name, timezone: "America/Cuiaba", startMethod: "MANUAL", memberships: { create: { userId: user.id, role: "VIEWER" } } } }))); propertyIds.push(...properties.map(p => p.id));
  const token = randomBytes(32).toString("hex");
  await db.session.create({ data: { tokenHash: digest(token), userId: user.id, activePropertyId: properties[0].id, expiresAt: new Date(Date.now() + 86400000) } });
  await context.addCookies([{ name: sessionCookie, value: token, url: "http://localhost:3000", httpOnly: true, sameSite: "Lax" }]);
  await page.goto("/app/assistant");
  await expect(page.getByRole("heading", { name: "Assistente no WhatsApp" })).toBeVisible();
  await page.getByRole("button", { name: "Conectar WhatsApp", exact: true }).click();
  await expect(page.locator(".whatsapp-code code")).toHaveText(/^AGROMIND [a-f0-9]{32}$/);
  const incoming = async () => {
    const text = await page.locator(".whatsapp-code code").innerText();
    const id = randomUUID();
    const raw = JSON.stringify({ object: "whatsapp_business_account", entry: [{ id: process.env.WHATSAPP_ACCOUNT_IDS, changes: [{ field: "messages", value: { metadata: { phone_number_id: process.env.WHATSAPP_PHONE_NUMBER_ID }, messages: [{ id, from: "556900001111", timestamp: String(Math.floor(Date.now() / 1000)), type: "text", text: { body: text } }] } }] }] });
    const r = await request.post("/api/webhooks/whatsapp", { headers: { "content-type": "application/json", "x-hub-signature-256": "sha256=" + createHmac("sha256", process.env.WHATSAPP_APP_SECRET!).update(raw).digest("hex") }, data: raw }); expect(r.status()).toBe(200);
    const row = await db.whatsappInboxEvent.findFirstOrThrow({ where: { accountId: process.env.WHATSAPP_ACCOUNT_IDS, encrypted: { not: "" }, processedAt: null }, orderBy: { receivedAt: "desc" } }); keys.push(row.eventKey);
    expect(await processWhatsappEvent(row.eventKey)).toBe(true);
  };
  await incoming();
  await expect(page.getByText("WhatsApp conectado", { exact: true })).toBeVisible({ timeout: 10000 });
  await expect(page.getByRole("heading", { name: "Sítio Girassol" })).toBeVisible();
  await expect(page.locator(".whatsapp-code")).toHaveCount(0);
  await expect(page.getByText("1111", { exact: true })).toBeVisible();
  await page.getByLabel("Propriedade para as consultas").selectOption(properties[1].id);
  await page.getByRole("button", { name: "Gerar código para trocar conexão" }).click();
  await incoming();
  await expect(page.getByRole("heading", { name: "Fazenda Horizonte" })).toBeVisible({ timeout: 10000 });
  await page.screenshot({ path: "../../tmp/whatsapp-connected-desktop.png", fullPage: true });
  const audit = await new AxeBuilder({ page }).analyze(); expect(audit.violations).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "../../tmp/whatsapp-connected-mobile.png", fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Desconectar WhatsApp", exact: true }).click();
  await expect(page.getByText("Conecte seu telefone", { exact: true })).toBeVisible();
  expect(await db.whatsappConnection.count({ where: { userId: user.id } })).toBe(0);
});
